// 분석 결과의 신선도 기준 — 한 곳에서만 정한다.
//
// 값이 둘인 이유(하나로 합치면 안 된다): 한 바퀴(전체 갱신이 등록 소환사를 한 번 도는 시간)를
// 사이에 두고 두 기준이 서로 반대쪽에 있어야 한다. 2026-09-12 실측 한 바퀴 = 6.4일(시간당 165명).
//
//   스윕 건너뛰기(SWEEP_SKIP) < 한 바퀴 ≤ 신선도(FRESH_MAX_AGE)
//
// · SWEEP_SKIP 이 한 바퀴보다 길면: 스윕이 돌아왔을 때 아직 "건너뛰기" 구간이라 전원을 지나쳐
//   아무 갱신도 못 한다(DB만 훑는 헛바퀴).
// · FRESH_MAX_AGE 가 한 바퀴보다 짧으면: 스윕이 돌아오기 전에 전부 스테일이 되어
//   '정밀 스테일'이 영원히 재생성된다(예전 72시간 기준에서 실제로 그랬다).
//
// 한 바퀴 시간이 크게 바뀌면(시드 증가, 프로덕션 키로 한도 9배 상승 등) 두 값을 다시 잡아야 한다.
// 확인: 어드민 전체 갱신 카드의 진행 속도, 또는 refresh-all:state 의 cursor/passStartedAt.

/** 신선하다고 볼 기간 — 상태 라벨(정밀 최신/스테일), 전체 갱신 큐 우선순위,
 *  소환사 페이지 방문 시 재분석 트리거에 쓴다. 한 바퀴(6.4일)보다 길게 잡아 스테일 누적을 막는다.
 *  새 경기를 하면 매치 ID가 달라져 이 기간과 무관하게 즉시 재분석되므로, 이 값은
 *  "경기를 안 한 사람의 로비 참가자 랭크를 얼마나 묵혀도 되는가"에 가깝다. */
export const FRESH_MAX_AGE_HOURS = 168; // 7일
export const FRESH_MAX_AGE_MS = FRESH_MAX_AGE_HOURS * 60 * 60_000;

/** 전체 갱신 스윕이 "최근에 했으니 지나친다"고 볼 기간.
 *  한 바퀴보다 짧아야 돌아왔을 때 실제로 갱신이 일어난다. */
export const SWEEP_SKIP_MS = 120 * 60 * 60_000; // 5일
