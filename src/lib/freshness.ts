// 분석 결과를 "신선하다"고 볼 기간 — 한 곳에서만 정한다.
//
// 예전엔 72시간이 store.ts(SQL)·deep-jobs.ts(ms)에 따로 박혀 있고 스윕은 36시간을 따로 썼다. 지금은 셋 다 이 값:
//   · 상태 라벨·전체 갱신 큐 우선순위 (정밀 최신 / 정밀 스테일)
//   · 소환사 페이지 방문 시 재분석 트리거 (새 경기가 없어도 이 기간이 지나면 다시 분석)
//   · 전체 갱신 스윕의 건너뛰기 기준 (이 기간 안에 분석된 사람은 지나친다)
// 스윕 기준을 더 짧게 잡아 "곧 스테일 될 사람"을 미리 갱신하는 방식도 있지만, 한 바퀴(7일 이상)가
// 이 기간보다 길어 어차피 따라잡지 못한다 — 그 상황에선 아직 신선한 결과를 다시 분석하는 게 순수 낭비다.
//
// 120시간(5일)인 이유: 한 바퀴(2.5만 명)가 개발 키 한도에서 7일 넘게 걸린다(2026-09 실측).
// 3일 기준으로는 돌아오기도 전에 전부 스테일이 되어 '정밀 스테일'이 무한 재생성됐다.
// 새 경기를 하면 매치 ID가 달라져 이 기간과 무관하게 즉시 재분석되므로, 이 값은
// "경기를 안 한 사람의 로비 참가자 랭크를 얼마나 오래 묵혀도 되는가"에 가깝다.
export const FRESH_MAX_AGE_HOURS = 120;
export const FRESH_MAX_AGE_MS = FRESH_MAX_AGE_HOURS * 60 * 60_000;
