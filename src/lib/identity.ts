// 소환사 식별자 정규화.
//
// 라이엇 태그에는 전각 문자가 들어갈 수 있다(예: 괴물쥐#ＫR1). 전각 Ｋ를 그냥
// toLowerCase()하면 전각 ｋ가 되고, NFKC로 먼저 접으면 반각 k가 된다. 그래서
// 페이지(NFKC 적용)와 크론·API 라우트(미적용)가 같은 계정을 서로 다른 키로
// 취급해, 한 계정이 두 벌로 분석·저장되는 문제가 있었다.
//
// 정규화를 진입점마다 챙기는 대신 키를 만드는 지점(저장 계층·잡 키·API 캐시
// 키)에서 이 함수를 쓴다 — 호출자가 무엇을 넘기든 같은 계정은 같은 키가 된다.
export function canon(s: string): string {
  return s.normalize("NFKC").toLowerCase();
}
